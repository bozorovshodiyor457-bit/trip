export const useTranslation = (lang) => {
  return (key, params = {}) => {
    let text = translations[lang]?.[key] || translations['UZ'][key] || key;
    
    // Replace parameters
    Object.keys(params).forEach(param => {
      text = text.replace(`{${param}}`, params[param]);
    });
    
    return text;
  };
};
